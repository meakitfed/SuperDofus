"""P2.12a: the achievements the sim can follow -> game/data/achievements.json (compact, committed).

    python gamedata.py achievements

From the Dofus 3 tables achievements / achievementobjectives / achievementrewards / achievementcategories.
An objective is a criterion (achievementobjectives.criterion) read by CriteriaEval. An achievement is kept when
every one of its objectives uses a key the sim follows (SUPPORTED); the others wait for the lot that adds their event.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# PL level · Qf / QF quest finished · ES subarea visited · EM monster beaten · EI item used ·
# OA achievement obtained · Oa achievement points · PO item owned
SUPPORTED = {"PL", "Qf", "QF", "ES", "EM", "EI", "OA", "Oa", "PO"}


def _keys(criterion: str) -> set[str]:
    return {m for m in re.findall(r"(?:^|[(&|])\s*([A-Za-z]{2})(?=[<>=!])", criterion)}


def run(table) -> None:
    ach_t = table("achievementsdataroot")
    obj_t = table("achievementobjectivesdataroot")
    rew_t = table("achievementrewardsdataroot")
    cat_t = table("achievementcategoriesdataroot")
    out: dict[str, dict] = {}
    for a in ach_t.values():
        objs = [obj_t[str(i)] for i in a["objectiveIds"] if str(i) in obj_t]
        if not objs or len(objs) != len(a["objectiveIds"]):
            continue
        if any(not _keys(o["criterion"]) or not _keys(o["criterion"]) <= SUPPORTED for o in objs):
            continue
        rewards = []
        for rid in a["rewardIds"]:
            r = rew_t.get(str(rid))
            if r is None:
                continue
            rewards.append({"criteria": r["criterions"], "xp": float(r["experienceRatio"]), "kamas": float(r["kamasRatio"]),
                            "scale": int(r["kamasScaleWithPlayerLevel"]),
                            "items": [[int(i), int(q)] for i, q in zip(r["itemsReward"], r["itemsQuantityReward"])],
                            "emotes": [int(e) for e in r["emotesReward"]], "spells": [int(e) for e in r["spellsReward"]],
                            "titles": [int(e) for e in r["titlesReward"]]})
        out[str(a["id"])] = {"id": int(a["id"]), "name_id": int(a["nameId"]), "desc_id": int(a["descriptionId"]),
                             "category": int(a["categoryId"]), "icon": int(a["iconId"]), "points": int(a["points"]),
                             "level": int(a["level"]), "order": int(a["order"]),
                             "objectives": [{"id": int(o["id"]), "name_id": int(o["nameId"]), "criterion": o["criterion"]} for o in sorted(objs, key=lambda o: o["order"])],
                             "rewards": rewards}
    used = {a["category"] for a in out.values()}
    cats = {}
    while True:
        more = {int(cat_t[str(u)]["parentId"]) for u in used if str(u) in cat_t and int(cat_t[str(u)]["parentId"]) > 0} - used
        if not more:
            break
        used |= more
    for u in sorted(used):
        c = cat_t.get(str(u))
        if c:
            cats[str(u)] = {"id": int(c["id"]), "name_id": int(c["nameId"]), "parent": int(c["parentId"]), "order": int(c["order"]),
                            "icon": c["icon"]}
    path = ROOT / "game" / "data" / "achievements.json"
    path.write_text(json.dumps({"_doc": "Generated by tools/extractor/gamedata.py achievements (Dofus 3 achievements tables, P2.12a).",
                                "achievements": out, "categories": cats}, separators=(",", ":")), encoding="utf-8")
    print(f"  achievements: {len(out)} of {len(ach_t)}, {len(cats)} categories -> {path} ({path.stat().st_size // 1024} Ko)")
