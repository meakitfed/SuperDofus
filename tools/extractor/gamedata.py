"""
Dofus 3 game tables -> game/data (read by shared/game_data.gd).

    python gamedata.py experience        # game/data/experience.json: total XP to reach each level
    python gamedata.py shops dofus               # game/worlds/dofus/shops.json: what the real merchants sell (+ their items)
    python gamedata.py interactives incarnam   # game/worlds/incarnam/interactives.json (harvestable elements) + tables skills, jobs
    python gamedata.py quests incarnam   # game/worlds/incarnam/quests.json (after npcs, before items)
    python gamedata.py items incarnam    # game/data/items.json: the items the monsters of a world drop
                                         # + their icons in Content/Picto/Items/<icon>.webp
    python gamedata.py items incarnam            # game/data/items.json: the world's drops + EXTRA_ITEMS, with effects
    python gamedata.py table breeds [--fields id,maleLook] [--ids 1,2]
                                         # game/data/tables/breeds.json: a light copy of a table
                                         # (GameData.table("breeds") reads it before the raw content)

maps.py world runs both after writing a world.
"""
