def _table(name: str) -> dict:
    path = CONTENT / "Data" / f"{name}.json"
    if not path.exists():
        UnityPy.config.FALLBACK_UNITY_VERSION = detect_unity_version(DEFAULT_GAME)
        Extractor(DEFAULT_GAME, CONTENT.parent, "webp").data(name)
    return json.loads(path.read_text(encoding="utf-8"))["objectsById"]


def experience() -> None:
    xp = _table("characterxpmappingsdataroot")
    levels = [int(xp[str(lv)]["experiencePoints"]) for lv in range(1, MAX_LEVEL + 1)]
    (DATA / "experience.json").write_text(json.dumps({
        "_doc": "Generated by tools/extractor/gamedata.py (Dofus 3 characterxpmappings): levels[i] = total XP of level i+1.",
        "levels": levels}), encoding="utf-8")
    print(f"  experience: {len(levels)} levels -> {DATA / 'experience.json'}")


