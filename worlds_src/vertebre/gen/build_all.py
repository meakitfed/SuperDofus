"""Builds the whole Vertebre world into game/worlds/vertebre:  python build_all.py [--only classes,mobs,...]

Order matters for ids (deterministic): classes, mobs, items, world. Everything is regenerated from the spec."""
from __future__ import annotations

import os
import shutil
import sys
import time

_t0 = time.time()


def step(msg):
    print("[%5.1fs] %s" % (time.time() - _t0, msg), flush=True)

from common import CONTENT, DATA, OUT, R, T, WORLD_ID, dump

import rigs
from dofus_bone import render_frame  # noqa: F401  (also puts joss build dir on the path)


REUSE = "--reuse" in sys.argv
OBJECTIVE_TEXTS = {395670: "Aller voir #1", 56304: "Retourner voir #1", 114533: "Rapporter #3 x #2 à #1", 56293: "Découvrir : #1", 154393: "Découvrir : #1",
                   114534: "Vaincre #2 x #1", 114535: "Vaincre #2 x #1", 56297: "Vaincre : #1", 56295: "Explorer", 56296: "Montrer #3 x #2 à #1"}


def write_bones():
    """Writes every bone; with --reuse, a bone whose spec and drawing code did not change is left as it is."""
    import hashlib
    folder = os.path.join(CONTENT, "Characters", "Bones")
    code = open(rigs.__file__, "rb").read()
    for bid, spec in R.bones.items():
        target = os.path.join(folder, bid)
        digest = hashlib.sha1(code + repr(sorted(spec.items(), key=lambda kv: kv[0])).encode()).hexdigest()
        stamp = os.path.join(target, ".spec")
        if REUSE and os.path.exists(stamp) and open(stamp).read() == digest:
            continue
        rigs.build(bid, spec).write(target)
        open(stamp, "w").write(digest)
    open(os.path.join(OUT, "Content", ".gdignore"), "w").close()


def write_icons():
    for rel, fn in R.icons:
        path = os.path.join(CONTENT, rel + ".png")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        fn().save(path, optimize=True)


def write_data():
    dump(os.path.join(DATA, "spells.json"), {"_doc": "Generated by worlds_src/vertebre/gen (Vertebre world)", "classes": R.classes, "grades": R.grades,
                                            "spells": R.spells, "summons": R.summons})
    if R.items or R.sets:
        dump(os.path.join(DATA, "items.json"), {"items": R.items, "sets": R.sets})
    for name, rows in R.tables.items():
        dump(os.path.join(DATA, "tables", name + ".json"), {"objectsById": rows})
    dump(os.path.join(CONTENT, "I18n", "extra_fr.json"), {str(k): v for k, v in T.by_id.items()}, indent=None)


def main():
    if os.path.isdir(OUT):
        for sub in ("data", "maps", "Content/Maps", "Content/I18n") + (() if REUSE else ("Content",)):
            shutil.rmtree(os.path.join(OUT, sub), ignore_errors=True)
    import classes
    classes.build()
    step('classes')
    import items
    items.build()
    step('items')
    import mobs, bosses
    bosses.make_minions()
    mobs.build_regular()
    bosses.build_bosses()
    step('mobs')
    import story, world
    story.alloc()
    M = world.build()
    step('world')
    import dofus_skin
    dofus_skin.apply(world._look_bone)
    world.write_all()
    # objective sentences: the engine's own templates (questobjectivetypes) are Dofus texts, replaced here by ours
    for nid, text in OBJECTIVE_TEXTS.items():
        T.by_id[nid] = text
    write_bones()
    step('bones')
    write_icons()
    step('icons')
    dofus_skin.copy_assets()
    write_data()
    import docs
    docs.write()
    print("items", len(R.items), "sets", len(R.sets), "monsters", len(R.monsters), "bosses", len(R.bosses), "spells", len(R.spells), "summons", len(R.summons), "bones", len(R.bones), "icons", len(R.icons), "texts", len(T.by_id))


if __name__ == "__main__":
    main()
